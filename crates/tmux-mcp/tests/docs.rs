fn append_tools(output: &mut String) -> TestResult {
    let tools = TmuxTools::builder(libtmux::Server::new()?)
        .selection(Selection::parse(
            Some("inspect,manage,execute,teardown"),
            None,
            None,
        )?)
        .build();
    for tool in tools.offered() {
        let row = tool
            .meta
            .as_ref()
            .and_then(|meta| meta.0.get("com.git-pull.libtmux-mcp/capability"))
            .expect("capability row");
        writeln!(output, "\n## `{}`\n", tool.name)?;
        writeln!(
            output,
            "{}\n",
            tool.description.as_deref().expect("controlled description")
        )?;
        writeln!(output, "- Toolset: `{}`", row["toolset"].as_str().unwrap())?;
        writeln!(
            output,
            "- Process reach: `{}`",
            row["processReach"].as_str().unwrap()
        )?;
        writeln!(
            output,
            "- Tmux effects: `{}`",
            serde_json::to_string(&row["tmuxEffects"])?
        )?;
        writeln!(
            output,
            "- Output classes: `{}`",
            serde_json::to_string(&row["outputClasses"])?
        )?;
        writeln!(
            output,
            "- May expose secrets: `{}`",
            row["mayExposeSecrets"].as_bool().unwrap()
        )?;
        writeln!(
            output,
            "- May return untrusted content: `{}`",
            row["mayReturnUntrustedContent"].as_bool().unwrap()
        )?;
        let mut hints = serde_json::to_value(tool.annotations.as_ref().expect("annotations"))?;
        hints.as_object_mut().expect("hint object").remove("title");
        writeln!(
            output,
            "- Whole-call annotations: `{}`",
            serde_json::to_string(&hints)?
        )?;
        writeln!(
            output,
            "- Input literalization: `{}`",
            serde_json::to_string(&row["inputLiteralization"])?
        )?;
        writeln!(
            output,
            "- Nested authority: `{}`",
            serde_json::to_string(&row["nestedAuthority"])?
        )?;
        writeln!(
            output,
            "- Amplifies future input: `{}`",
            row["amplifiesFutureInput"].as_bool().unwrap()
        )?;
    }
    Ok(())
}

#[test]
